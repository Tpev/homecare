import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {env,root} from '../../find-care-screen-audit-2026-09-08/capture/environment.mjs';
import {output} from './environment.mjs';
const database=path.resolve(env.DB_DATABASE);
const expected=path.join(root,'.tmp/find-care-screen-audit-2026-09-08/find-care-audit.sqlite');
if(database!==expected||env.DB_CONNECTION!=='sqlite'||env.APP_ENV!=='playwright'||env.APP_URL!=='http://127.0.0.1:8028')throw new Error('Unexpected runtime environment; migration refused');
const run=(args)=>execFileSync('php',args,{cwd:root,env,encoding:'utf8',windowsHide:true});
const beforeStatus=run(['artisan','migrate:status','--no-ansi']);
const pending=beforeStatus.split('\n').filter(line=>line.includes('Pending')).map(line=>line.trim().split(/\s/)[0]);
if(pending.some(name=>name!=='2026_09_09_000001_create_care_pricing_agreements'))throw new Error('Unexpected pending migrations: '+pending.join(', '));
if(!pending.length){console.log('No pending migration; no changes made');process.exit(0);}
const runtime=path.join(root,'.tmp/find-care-recruitment-polish-2026-09-09');fs.mkdirSync(runtime,{recursive:true});
const backup=path.join(runtime,'before-pricing-migration-'+new Date().toISOString().replaceAll(/[:.]/g,'-')+'.sqlite');
if(fs.existsSync(database+'-wal')||fs.existsSync(database+'-journal'))throw new Error('Active SQLite journal found; use a transactional backup instead');
const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const originalHash=hash(database);fs.copyFileSync(database,backup,fs.constants.COPYFILE_EXCL);
if(hash(database)!==originalHash||hash(backup)!==originalHash)throw new Error('Database changed while copying; migration refused until a consistent backup is available');
const integrity=JSON.parse(run([path.join(output,'qa/verify-runtime-copy.php'),backup]));
const result={at:new Date().toISOString(),database,backup,backupSha256:originalHash,backupIntegrity:integrity.integrity,pending,changes:'Existing repository migration creates an empty care_pricing_agreements table and nullable pricing references/fee policy columns. No reset, reseed, or fixture date changes.'};
fs.writeFileSync(path.join(output,'runtime-migration.json'),JSON.stringify(result,null,2));
console.log('Verified backup '+backup);
result.migrationOutput=run(['artisan','migrate','--force','--no-ansi']);
result.afterStatus=run(['artisan','migrate:status','--no-ansi']).split('\n').filter(line=>line.includes('2026_09_09_000001')||line.includes('Pending'));
result.passed=result.afterStatus.some(line=>line.includes('Ran'))&&!result.afterStatus.some(line=>line.includes('Pending'));
fs.writeFileSync(path.join(output,'runtime-migration.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
if(!result.passed)process.exitCode=1;
