import { expect, test } from '@playwright/test';
import { loginAs } from '../helpers/auth';

test('family purchases, private contribution page, and admin tracking stay clear on desktop and mobile', async ({ page, browser }, testInfo) => {
    const pageErrors: string[] = [];
    page.on('pageerror', error => pageErrors.push(error.message));
    await loginAs(page, 'family');
    await page.goto('/family/care-hours');
    await expect(page.getByRole('heading', { name: 'Care hours for Margaret E2E' })).toBeVisible();
    await expect(page.getByRole('region', { name: 'Care hours balance' })).toContainText('0 h');

    await page.getByRole('link', { name: 'Buy hours', exact: true }).click();
    await expect(page.getByRole('heading', { name: /Margaret E2E/ })).toBeVisible();
    await page.locator('input[name="hours"][value="5"]').check();
    await page.locator('input[name="terms"]').check();
    await page.getByRole('button', { name: 'Continue to payment' }).click();
    await expect(page).toHaveURL(/\/family\/care-hours\/purchases\//);
    await expect(page.getByText(/5 (care )?hours added|5 h added|Hours added/i).first()).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('purchase-receipt.png'), fullPage: true });

    await page.goto('/family/care-hours');
    await expect(page.getByRole('region', { name: 'Care hours balance' })).toContainText('5 h');
    await page.getByRole('link', { name: 'Buy hours', exact: true }).click();
    await expect(page.locator('label').filter({ has: page.locator('input[name="hours"][value="10"]') })).toContainText('+ 1 h free');
    await page.screenshot({ path: testInfo.outputPath('packages-desktop.png'), fullPage: true });
    await page.locator('input[name="hours"][value="10"]').check();
    await page.locator('input[name="terms"]').check();
    await page.getByRole('button', { name: 'Continue to payment' }).click();
    await expect(page).toHaveURL(/\/family\/care-hours\/purchases\//);
    await expect(page.getByText(/11 (care )?hours added|11 h added|Hours added/i).first()).toBeVisible();
    await page.goto('/family/care-hours');
    await expect(page.getByRole('region', { name: 'Care hours balance' })).toContainText('16 h');
    await page.screenshot({ path: testInfo.outputPath('care-hours-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 375, height: 812 });
    await expect(page.getByRole('heading', { name: 'Care hours for Margaret E2E' })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
    await page.screenshot({ path: testInfo.outputPath('care-hours-mobile.png'), fullPage: true });

    await page.locator('summary').filter({ hasText: 'Let someone contribute' }).click();
    await page.getByRole('button', { name: 'Create private link' }).click();
    const giftUrl = await page.getByLabel('Your private link').inputValue();
    const donorContext = await browser.newContext({ viewport: { width: 375, height: 812 } });
    const donor = await donorContext.newPage();
    const giftResponse = await donor.goto(giftUrl);
    expect(giftResponse?.headers()['referrer-policy']).toBe('no-referrer');
    await expect(donor.getByRole('heading', { name: /Margaret E2E/ })).toBeVisible();
    await expect(donor.getByText('16 h', { exact: true })).toHaveCount(0);
    await expect(donor.getByRole('region', { name: 'Available care packages' }).or(donor.locator('[aria-label="Available care packages"]'))).toBeVisible();
    await expect(donor.getByText('+ 1 h free', { exact: true })).toHaveCount(0);
    expect(await donor.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
    await donor.screenshot({ path: testInfo.outputPath('contribution-mobile.png'), fullPage: true });
    await donorContext.close();

    await page.setViewportSize({ width: 1280, height: 900 });
    await page.goto('/family/requests/1?tab=applicants');
    await page.getByTestId('hire-caregiver').click();
    await expect(page.getByRole('radio', { name: /Use care hours/ })).toBeChecked();
    await page.getByRole('radio', { name: 'Usual card payment', exact: true }).check();
    await expect(page.getByRole('complementary', { name: 'Care price estimate' })).toContainText('$62.00');
    await page.getByRole('radio', { name: /Use care hours/ }).check();
    await expect(page.getByRole('complementary', { name: 'Care hours coverage' })).toContainText(/Remaining payment\s*\$0\.00/);
    await expect(page.getByRole('complementary', { name: 'Care hours coverage' })).toContainText('Nothing to pay for scheduled care.');
    await expect(page.getByRole('complementary', { name: 'Care price estimate' })).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('booking-review-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Confirm hire', exact: true }).click();
    const coverage = page.getByRole('region', { name: 'Care-hour payment', exact: true });
    await expect(coverage).toContainText('2 h reserved for this visit.');
    await expect(coverage).toContainText('Scheduled care is covered.');
    await expect(page.getByText('Confirm card authorization', { exact: true })).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('booking-covered-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 375, height: 812 });
    await coverage.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
    await page.screenshot({ path: testInfo.outputPath('booking-covered-mobile.png'), fullPage: true });
    await page.goto('/family/care-hours');
    await expect(page.getByRole('region', { name: 'Care hours balance' })).toContainText('14 h');
    await expect(page.getByRole('region', { name: 'Care hours balance' })).toContainText('2 h reserved');

    await page.setViewportSize({ width: 1280, height: 900 });
    await loginAs(page, 'admin');
    await page.goto('/admin/care-hours');
    await expect(page.getByRole('heading', { name: /Care.hours/i }).first()).toBeVisible();
    await page.getByRole('link', { name: /Margaret E2E/ }).click();
    await expect(page.getByRole('heading', { name: /Margaret E2E/ }).first()).toBeVisible();
    await expect(page.getByText('$310.00', { exact: false }).first()).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('admin-account-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 375, height: 812 });
    await expect(page.getByRole('heading', { name: /Margaret E2E/ }).first()).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
    await page.screenshot({ path: testInfo.outputPath('admin-account-mobile.png'), fullPage: true });
    expect(pageErrors).toEqual([]);
});

test('prepaid booking with a shortfall uses a separate one-off payment', async ({ page }, testInfo) => {
    const pageErrors: string[] = [];
    page.on('pageerror', error => pageErrors.push(error.message));
    await loginAs(page, 'familyEligible');
    await page.goto('/family/care-hours');
    await expect(page.getByRole('region', { name: 'Care hours balance' })).toContainText('1 h 30 min');
    await page.goto('/family/requests/3?tab=applicants');
    await page.getByTestId('hire-caregiver').click();
    await expect(page.getByRole('radio', { name: /Use care hours/ })).toBeChecked();
    await page.getByRole('radio', { name: /Use care hours/ }).check();
    await expect(page.getByRole('complementary', { name: 'Care hours coverage' })).toContainText(/Remaining payment\s*\$15\.50/);
    await expect(page.getByRole('complementary', { name: 'Care price estimate' })).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('booking-shortfall-review-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Confirm hire', exact: true }).click();
    const coverage = page.getByRole('region', { name: 'Care-hour payment', exact: true });
    await expect(coverage).toContainText('1 h 30 min reserved');
    await expect(coverage).toContainText('30 min still needs payment · $15.50');
    await expect(coverage).toContainText('You can pay this amount without saving a card.');
    await page.screenshot({ path: testInfo.outputPath('booking-shortfall-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 375, height: 812 });
    await coverage.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
    await page.screenshot({ path: testInfo.outputPath('booking-shortfall-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: 'Pay $15.50', exact: true }).click();
    await expect(page).toHaveURL(/\/family\/requests\/3/);
    await expect(coverage).toContainText('Scheduled care is covered.');
    await expect(page.getByRole('button', { name: 'Pay $15.50', exact: true })).toHaveCount(0);
    await expect(page.getByText('Confirm card authorization', { exact: true })).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('booking-shortfall-paid-mobile.png'), fullPage: true });
    expect(pageErrors).toEqual([]);
});
